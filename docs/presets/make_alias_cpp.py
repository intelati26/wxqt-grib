#!/usr/bin/env python3
"""Writes src/gfs/ChartAliasData.cpp from docs/presets/alias-table.csv (run build_presets.py first): python3 docs/presets/make_alias_cpp.py"""
import csv, os
here = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(here, 'alias-table.csv'))))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['// *****************************************************************************',
       '// * This file is part of wxqt.  Licensed under the GNU General Public License v3.',
       '// * See the COPYING file for the full license text.',
       '// *****************************************************************************',
       '',
       '// Generated by docs/presets/make_alias_cpp.py from docs/presets/alias-table.csv: every chart id read as a family and its settings. Edit the script or the table, not this file.',
       '',
       '#include "gfs/ChartAlias.h"',
       '',
       'namespace ChartAlias {',
       'const std::vector<Entry>& table() {',
       '    static const std::vector<Entry> entries = {']
for r in rows:
    fam = r['family']
    out.append('        {%s, %s, %s, %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s},' % (
        q(r['id']), q(r['label']), q(r['category']), int(r['models']), q(fam), q(r['field']), q(r['level']), q(r['mode']), q(r['chance']), q(r['product']), q(r['window']), q(r['limit']), q(r['kind']), q(r['detail']), q(r['values']), q(r['contours']),
        'true' if r['barbs'] else 'false', 'true' if r['stream'] else 'false', 'true' if r['bands'] else 'false', q(r['group']), 'true' if r['single'] else 'false', 'true' if r['differs_by_model'] else 'false'))
out += ['    };', '    return entries;', '}', '}  // namespace ChartAlias', '']
open(os.path.join(here, '..', '..', 'src', 'gfs', 'ChartAliasData.cpp'), 'w').write('\n'.join(out))
print(len(rows), 'ids written')
