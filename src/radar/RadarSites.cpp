Sites * RadarSites::sites;

void RadarSites::initialize() {
    sites = new Sites(name, lat, lon, false);
}

vector<string> RadarSites::radars() {
    vector<string> radarList;
    addAll(radarList, nexradRadars());
    addAll(radarList, tdwrRadars());
    return radarList;
}

LatLon RadarSites::getLatLon(const string& radarSite) {
    auto lat1 = lat.at(radarSite);
    auto lon1 = "-" + lon.at(radarSite);
    return LatLon(lat1, lon1);
}

vector<string> RadarSites::nexradRadarCodes() {
    vector<string> radars;
    for (const auto& radar : sites->codeList) {
        if (!WString::startsWith(radar, "T") || radar == "TJUA") {
            radars.push_back(radar);
        }
    }
    return radars;
}

vector<string> RadarSites::tdwrRadarCodes() {
    vector<string> radars;
    for (const auto& radar : sites->codeList) {
        if (WString::startsWith(radar, "T") && radar != "TJUA") {
            radars.push_back(radar);
        }
    }
    return radars;
}

vector<string> RadarSites::nexradRadars() {
    vector<string> radars;
    for (const auto& radar : sites->nameList) {
        if (!WString::startsWith(radar, "T") || WString::startsWith(radar, "TJUA")) {
            radars.push_back(radar);
        }
    }
    return radars;
}

vector<string> RadarSites::tdwrRadars() {
    vector<string> radars;
    for (const auto& radar : sites->nameList) {
        if (WString::startsWith(radar, "T") && !WString::startsWith(radar, "TJUA")) {
            radars.push_back(radar);
        }
    }
    return radars;
}

string RadarSites::getName(const string& radarSite) {
    return name.at(radarSite);
}

int RadarSites::findRadarIndex(const string& radarF) {
    auto radar = radarF;
    auto radarList = radars();
    for (const auto& index : range(radarList.size())) {
        if (WString::startsWith(radarList[index], radar + ":")) {
            return index;
        }
    }
    return 0;
}

vector<Site> RadarSites::getNearest(const LatLon& location, int count, bool includeTdwr) {
    vector<Site> radarSites;
    vector<string> allRadars;
    addAll(allRadars, nexradRadarCodes());
    if (includeTdwr) {
        addAll(allRadars, tdwrRadarCodes());
    }
    for (const auto& radar : allRadars) {
        radarSites.push_back(
            Site::fromLatLon(radar, "", getLatLon(radar), LatLon::distance(location, getLatLon(radar))));
    }
    std::sort(
        radarSites.begin(),
        radarSites.end(),
        [] (const Site &a, const Site &b) { return a.distance < b.distance; });
    return vector<Site>{radarSites.begin(), radarSites.begin() + count};
}

string RadarSites::getNearestCode(const LatLon& location, bool includeTdwr) {
    return getNearest(location, 5, includeTdwr)[0].codeName;
}

